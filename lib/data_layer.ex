  # MSSQL errors 2627 (PRIMARY KEY / UNIQUE constraint) and 2601 (unique index)
  # are duplicate-key violations. The constraint/index name is embedded in the
  # message text; migrations name unique indexes `<table>_<identity>_index`,
  # which `find_constraint_data/2` maps back to the offending identity.
  # sobelow_skip ["DOS.StringToAtom"]
  defp handle_raised_error(
         %Tds.Error{
           mssql: mssql
         },
         _stacktrace,
         _context,
         resource
       )
       when is_map(mssql) and (mssql.number == 2627 or mssql.number == 2601) do
    message_text = mssql[:msg_text] || ""

    index_name = extract_duplicate_key_name(message_text)

    %{fields: fields, message: message} =
      find_constraint_data(resource, index_name)

    message = message || "has already been taken"

    {:error,
     fields
     |> Enum.map(fn field ->
       Ash.Error.Changes.InvalidAttribute.exception(
         field: field,
         message: message
       )
     end)}
  end

  defp handle_raised_error(error, stacktrace, _ecto_changeset, _resource) do
    {:error, Ash.Error.to_ash_error(error, stacktrace)}
  end

  # Parse the constraint/index name out of an MSSQL duplicate-key message.
  # 2627: "Violation of UNIQUE KEY constraint 'name'. ..."
  #       "Violation of PRIMARY KEY constraint 'name'. ..."
  # 2601: "Cannot insert duplicate key row in object '...' with unique index 'name'. ..."
  # sobelow_skip ["DOS.StringToAtom"]
  defp extract_duplicate_key_name(message) do
    cond do
      Regex.match?(~r/PRIMARY KEY constraint/i, message) ->
        :PRIMARY

      match = Regex.run(~r/UNIQUE KEY constraint '([^']+)'/i, message, capture: :all_but_first) ->
        match |> Enum.at(0) |> String.to_atom()

      match = Regex.run(~r/unique index '([^']+)'/i, message, capture: :all_but_first) ->
        match |> Enum.at(0) |> String.to_atom()

      true ->
        :PRIMARY
    end
  end

  defp find_constraint_data(resource, :PRIMARY) do
    %{
      fields: Ash.Resource.Info.primary_key(resource),
      message: nil
    }
  end

  defp find_constraint_data(resource, index_name) do
    find_custom_index(resource, index_name) || find_identity(resource, index_name) ||
      %{fields: Ash.Resource.Info.primary_key(resource), message: nil}
  end

  defp find_custom_index(resource, searched_name) do
    table = AshMssql.DataLayer.Info.table(resource)

    resource
    |> AshMssql.DataLayer.Info.custom_indexes()
    |> Enum.find(fn custom_index ->
      name = AshMssql.CustomIndex.name(table, custom_index)
      name == searched_name
    end)
  end

  defp find_identity(resource, searched_index_name) do
    table = AshMssql.DataLayer.Info.table(resource)

    searched_identity_name =
      searched_index_name
      |> to_string()
      |> String.replace_prefix("#{table}_", "")
      |> String.replace_suffix("_index", "")

    identity =
      resource
      |> Ash.Resource.Info.identities()
      |> Enum.find(fn identity ->
        to_string(identity.name) == searched_identity_name
      end)

    case identity do
      nil -> nil
      identity -> %{fields: identity.keys, message: identity.message}
    end
  end

  defp set_table(record, changeset, operation, table_error?) do
    if AshMssql.DataLayer.Info.polymorphic?(record.__struct__) do
      table =
        changeset.context[:data_layer][:table] ||
          AshMssql.DataLayer.Info.table(record.__struct__)

      if table do
        Ecto.put_meta(record, source: table)
      else
        if table_error? do
          raise_table_error!(changeset.resource, operation)
        else
          record
        end
      end
    else
      record
    end
  end

  def from_ecto({:ok, result}), do: {:ok, from_ecto(result)}
  def from_ecto({:error, _} = other), do: other

  def from_ecto(nil), do: nil

  def from_ecto(value) when is_list(value) do
    Enum.map(value, &from_ecto/1)
  end

  def from_ecto(%resource{} = record) do
    if Spark.Dsl.is?(resource, Ash.Resource) do
      empty = struct(resource)

      resource
      |> Ash.Resource.Info.relationships()
      |> Enum.reduce(record, fn relationship, record ->
        case Map.get(record, relationship.name) do
          %Ecto.Association.NotLoaded{} ->
            Map.put(record, relationship.name, Map.get(empty, relationship.name))

          value ->
            Map.put(record, relationship.name, from_ecto(value))
        end
      end)
    else
      record
    end
  end

  def from_ecto(other), do: other

  def to_ecto(nil), do: nil

  def to_ecto(value) when is_list(value) do
    Enum.map(value, &to_ecto/1)
  end

  def to_ecto(%resource{} = record) do
    if Spark.Dsl.is?(resource, Ash.Resource) do
      resource
      |> Ash.Resource.Info.relationships()
      |> Enum.reduce(record, fn relationship, record ->
        value =
          case Map.get(record, relationship.name) do
            %Ash.NotLoaded{} ->
              %Ecto.Association.NotLoaded{
                __field__: relationship.name,
                __cardinality__: relationship.cardinality
              }

            value ->
              to_ecto(value)
          end

        Map.put(record, relationship.name, value)
      end)
    else
      record
    end
  end

