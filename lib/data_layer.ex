  defp update_defaults(resource) do
    attributes =
      resource
      |> Ash.Resource.Info.attributes()
      |> Enum.reject(&is_nil(&1.update_default))

    attributes
    |> static_defaults()
    |> Enum.concat(lazy_matching_defaults(attributes))
    |> Enum.concat(lazy_non_matching_defaults(attributes))
  end

  defp static_defaults(attributes) do
    attributes
    |> Enum.reject(&get_default_fun(&1))
    |> Enum.map(&{&1.name, &1.update_default})
  end

  defp lazy_non_matching_defaults(attributes) do
    attributes
    |> Enum.filter(&(!&1.match_other_defaults? && get_default_fun(&1)))
    |> Enum.map(fn attribute ->
      default_value =
        case attribute.update_default do
          function when is_function(function) ->
            function.()

          {m, f, a} when is_atom(m) and is_atom(f) and is_list(a) ->
            apply(m, f, a)
        end

      {attribute.name, default_value}
    end)
  end

  defp lazy_matching_defaults(attributes) do
    attributes
    |> Enum.filter(&(&1.match_other_defaults? && get_default_fun(&1)))
    |> Enum.group_by(& &1.update_default)
    |> Enum.flat_map(fn {default_fun, attributes} ->
      default_value =
        case default_fun do
          function when is_function(function) ->
            function.()

          {m, f, a} when is_atom(m) and is_atom(f) and is_list(a) ->
            apply(m, f, a)
        end

      Enum.map(attributes, &{&1.name, default_value})
    end)
  end

  defp get_default_fun(attribute) do
    if is_function(attribute.update_default) or match?({_, _, _}, attribute.update_default) do
      attribute.update_default
    end
  end

  @impl true
  def update(resource, changeset) do
    ecto_changeset =
      changeset.data
      |> Map.update!(:__meta__, &Map.put(&1, :source, table(resource, changeset)))
      |> ecto_changeset(changeset, :update)

    try do
      query = from(row in resource, as: ^0)

      # Atomics are computed in the database, so their values must come from
      # the reload. The action_select fields only fill in whatever the
      # changeset doesn't already carry — attributes written by this changeset
      # stay authoritative, so a concurrent writer (with `transaction?: false`)
      # can't leak its values into our result.
      reloaded_action_select =
        changeset.action_select
        |> List.wrap()
        |> Enum.concat(Ash.Resource.Info.always_selected_attribute_names(resource))
        |> Enum.uniq()
        |> Kernel.--(Keyword.keys(changeset.atomics) ++ Map.keys(changeset.attributes))

      select =
        Enum.uniq(
          Keyword.keys(changeset.atomics) ++
            reloaded_action_select ++ Ash.Resource.Info.primary_key(resource)
        )

      query =
        query
        |> AshSql.Bindings.default_bindings(
          resource,
          AshMssql.SqlImplementation,
          changeset.context
        )
        # |> Ecto.Query.select(^select)
        |> pkey_filter(changeset.data)

      case AshSql.Atomics.query_with_atomics(
             resource,
             query,
             changeset.filter,
             changeset.atomics,
             ecto_changeset.changes,
             []
           ) do
        {:ok, query} ->
          repo_opts = repo_opts(changeset.timeout, changeset.tenant, changeset.resource)

          # repo_opts =
          #  Keyword.put(repo_opts, :returning, Keyword.keys(changeset.atomics))

          repo = dynamic_repo(resource, changeset)

          {count, nil} =
            repo.update_all(query, [], repo_opts)

          result =
            from(row in resource, as: ^0, select: ^select)
            |> pkey_filter(changeset.data)
            |> repo.all(Keyword.take(repo_opts, [:prefix, :timeout]))

          case {count, result} do
            {0, []} ->
              {:error,
               Ash.Error.Changes.StaleRecord.exception(
                 resource: resource,
                 filters: changeset.filter
               )}

            {1, [result]} ->
              record =
                changeset.data
                |> Map.merge(changeset.attributes)
                |> Map.merge(
                  Map.take(result, Keyword.keys(changeset.atomics) ++ reloaded_action_select)
                )

              {:ok, record}
          end

        {:error, error} ->
          {:error, error}
      end
    rescue
      e ->
        handle_raised_error(e, __STACKTRACE__, ecto_changeset, resource)
    end
  end

  defp pkey_filter(query, %resource{} = record) do
    pkey =
      record
      |> Map.take(Ash.Resource.Info.primary_key(resource))
      |> Map.to_list()

    Ecto.Query.where(query, ^pkey)
  end

  @impl true
  def destroy(resource, %{data: record} = changeset) do
    ecto_changeset = ecto_changeset(record, changeset, :delete)

    try do
      ecto_changeset
      |> dynamic_repo(resource, changeset).delete(
        repo_opts(changeset.timeout, changeset.resource)
      )
      |> from_ecto()
      |> case do
        {:ok, _record} ->
          :ok

        {:error, error} ->
          handle_errors({:error, error})
      end
    rescue
      e ->
        handle_raised_error(e, __STACKTRACE__, ecto_changeset, resource)
    end
  end

  @impl true
  def sort(query, sort, _resource) do
    {:ok, Map.update!(query, :__ash_bindings__, &Map.put(&1, :sort, sort))}
  end

  @impl true
  def select(query, select, resource) do
    query = AshSql.Bindings.default_bindings(query, resource, AshMssql.SqlImplementation)

    {:ok,
     from(row in query,
       select: struct(row, ^Enum.uniq(select))
     )}
  end

  @doc false
