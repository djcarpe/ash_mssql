  defp add_exclusion_constraints(changeset, resource) do
    resource
    |> AshMssql.DataLayer.Info.exclusion_constraint_names()
    |> Enum.reduce(changeset, fn constraint, changeset ->
      case constraint do
        {key, name} ->
          Ecto.Changeset.exclusion_constraint(changeset, key, name: name)

        {key, name, message} ->
          Ecto.Changeset.exclusion_constraint(changeset, key, name: name, message: message)
      end
    end)
  end

  defp add_related_foreign_key_constraints(changeset, resource) do
    # TODO: this doesn't guarantee us to get all of them, because if something is related to this
    # schema and there is no back-relation, then this won't catch it's foreign key constraints
    resource
    |> Ash.Resource.Info.relationships()
    |> Enum.map(& &1.destination)
    |> Enum.uniq()
    |> Enum.flat_map(fn related ->
      related
      |> Ash.Resource.Info.relationships()
      |> Enum.filter(&(&1.destination == resource))
      |> Enum.map(&Map.take(&1, [:source, :source_attribute, :destination_attribute, :name]))
    end)
    |> Enum.reduce(changeset, fn %{
                                   source: source,
                                   source_attribute: source_attribute,
                                   destination_attribute: destination_attribute,
                                   name: relationship_name
                                 },
                                 changeset ->
      case AshMssql.DataLayer.Info.reference(resource, relationship_name) do
        %{name: name} when not is_nil(name) ->
          Ecto.Changeset.foreign_key_constraint(changeset, destination_attribute,
            name: name,
            message: "would leave records behind"
          )

        _ ->
          Ecto.Changeset.foreign_key_constraint(changeset, destination_attribute,
            name: "#{AshMssql.DataLayer.Info.table(source)}_#{source_attribute}_fkey",
            message: "would leave records behind"
          )
      end
    end)
  end

  defp add_my_foreign_key_constraints(changeset, resource) do
    resource
    |> Ash.Resource.Info.relationships()
    |> Enum.reduce(changeset, &Ecto.Changeset.foreign_key_constraint(&2, &1.source_attribute))
  end

  defp add_configured_foreign_key_constraints(changeset, resource) do
    resource
    |> AshMssql.DataLayer.Info.foreign_key_names()
    |> case do
      {m, f, a} -> List.wrap(apply(m, f, [changeset | a]))
      value -> List.wrap(value)
    end
    |> Enum.reduce(changeset, fn
      {key, name}, changeset ->
        Ecto.Changeset.foreign_key_constraint(changeset, key, name: name)

      {key, name, message}, changeset ->
        Ecto.Changeset.foreign_key_constraint(changeset, key, name: name, message: message)
    end)
  end

  defp add_unique_indexes(changeset, resource, ash_changeset) do
    changeset =
      resource
      |> Ash.Resource.Info.identities()
      |> Enum.reduce(changeset, fn identity, changeset ->
        name =
          AshMssql.DataLayer.Info.identity_index_names(resource)[identity.name] ||
            "#{table(resource, ash_changeset)}_#{identity.name}_index"

        opts =
          if Map.get(identity, :message) do
            [name: name, message: identity.message]
          else
            [name: name]
          end

        Ecto.Changeset.unique_constraint(changeset, identity.keys, opts)
      end)

    changeset =
      resource
      |> AshMssql.DataLayer.Info.custom_indexes()
      |> Enum.reduce(changeset, fn index, changeset ->
        opts =
          if index.message do
            [name: index.name, message: index.message]
          else
            [name: index.name]
          end

        Ecto.Changeset.unique_constraint(changeset, index.fields, opts)
      end)

    names =
      resource
      |> AshMssql.DataLayer.Info.unique_index_names()
      |> case do
        {m, f, a} -> List.wrap(apply(m, f, [changeset | a]))
        value -> List.wrap(value)
      end

    names =
      case Ash.Resource.Info.primary_key(resource) do
        [] ->
          names

        fields ->
          if table = table(resource, ash_changeset) do
            [{fields, table <> "_pkey"} | names]
          else
            []
          end
      end

    Enum.reduce(names, changeset, fn
      {keys, name}, changeset ->
        Ecto.Changeset.unique_constraint(changeset, List.wrap(keys), name: name)

      {keys, name, message}, changeset ->
        Ecto.Changeset.unique_constraint(changeset, List.wrap(keys), name: name, message: message)
    end)
  end

  # @impl true
  @impl true
  def upsert(resource, changeset, keys) do
    keys = keys || Ash.Resource.Info.primary_key(resource)

    if changeset.atomics in [nil, []] do
      upsert_via_merge(resource, changeset, keys)
    else
      # Atomic expressions reference the *existing* row, which a MERGE VALUES
      # source cannot express. Use insert-then-atomic-update-on-conflict, reusing
      # the same atomic-update machinery as `update/2`.
      upsert_with_atomics(resource, changeset, keys)
    end
  end

  defp upsert_via_merge(resource, changeset, keys) do
    update_defaults = update_defaults(resource)

    # Fields to update on conflict: everything explicitly changing, plus
    # update_defaults (e.g. updated_at), minus attributes that were merely
    # defaulted (e.g. created_at, so it is preserved) and the conflict keys.
    explicitly_changing_attributes =
      changeset.attributes
      |> Map.keys()
      |> Enum.concat(Keyword.keys(update_defaults))
      |> Kernel.--(Map.get(changeset, :defaults, []))
      |> Kernel.--(keys)

    upsert_fields =
      changeset.context[:private][:upsert_fields] || explicitly_changing_attributes

    case bulk_create(resource, [changeset], %{
           single?: true,
           upsert?: true,
           tenant: changeset.tenant,
           upsert_keys: keys,
           upsert_fields: upsert_fields,
           action_select: changeset.action_select,
           return_records?: true
         }) do
      {:ok, [result]} ->
        {:ok, result}

      {:ok, []} ->
        {:ok, nil}

      {:error, error} ->
        {:error, error}
    end
  end

  # Upserts with atomics run inside an Ash transaction, so we cannot rely on
  # catching a unique-violation and continuing (a failed statement dooms the
  # transaction). Instead we check for the existing row by key and branch to an
  # atomic UPDATE or an INSERT, relying on the surrounding transaction for
  # isolation. (Non-atomic upserts use a single atomic MERGE; this SELECT-then-
  # write path is only for the atomic case and is not hardened against a
  # concurrent insert of the same key outside a serializable transaction.)
  defp upsert_with_atomics(resource, changeset, keys) do
    repo = dynamic_repo(resource, changeset)
    key_values = Enum.map(keys, fn key -> {key, Map.get(changeset.attributes, key)} end)

    existing =
      from(row in resource, as: ^0)
      |> Ecto.Query.where(^key_values)
      |> repo.one()

    if existing do
      atomic_conflict_update(resource, changeset, keys, repo)
    else
      source = resolve_source(resource, changeset)

      opts =
        case changeset.context[:data_layer][:schema] do
          nil -> repo_opts(nil, changeset.tenant, resource)
          schema -> Keyword.put(repo_opts(nil, changeset.tenant, resource), :prefix, schema)
        end

      action_select = action_select_with_required(changeset.action_select, resource)

      case insert_all_returning(
             source,
             [changeset.attributes],
             repo,
             resource,
             action_select,
             opts
           ) do
        {_count, [record]} -> {:ok, record}
        {_count, _} -> {:ok, nil}
      end
    end
  end

  # Apply the atomics (and any other upsert fields) as an UPDATE to the
  # conflicting row, then reload it. Mirrors `update/2`'s atomic handling.
  defp atomic_conflict_update(resource, changeset, keys, repo) do
    ecto_changeset = ecto_changeset(changeset.data, changeset, :create, false)
    key_values = Enum.map(keys, fn key -> {key, Map.get(changeset.attributes, key)} end)
    atomic_keys = Keyword.keys(changeset.atomics)
    update_defaults = update_defaults(resource)

    upsert_fields =
      (changeset.context[:private][:upsert_fields] ||
         Map.keys(changeset.attributes) ++ Keyword.keys(update_defaults))
      |> Kernel.--(Map.get(changeset, :defaults, []))
      |> Kernel.--(keys)
      |> Kernel.--(atomic_keys)

    changes = Map.take(ecto_changeset.changes, upsert_fields)

    query =
      from(row in resource, as: ^0)
      |> AshSql.Bindings.default_bindings(resource, AshMssql.SqlImplementation, changeset.context)
      |> Ecto.Query.where(^key_values)

    case AshSql.Atomics.query_with_atomics(
           resource,
           query,
           changeset.filter,
           changeset.atomics,
           changes,
           []
         ) do
      {:ok, query} ->
        repo.update_all(query, [], repo_opts(nil, changeset.tenant, resource))

        # Atomics are computed in the database, so they must be part of the
        # reload even when the action's select doesn't ask for them.
        reload_select =
          case action_select_with_required(changeset.action_select, resource) do
            nil -> nil
            fields -> Enum.uniq(fields ++ atomic_keys)
          end

        result =
          from(row in resource, as: ^0)
          |> Ecto.Query.where(^key_values)
          |> apply_action_select(reload_select)
          |> repo.all()
          |> List.first()

        {:ok, result}

      {:error, error} ->
        {:error, error}
    end
  end

